-- Row Level Security
alter table public.land_records enable row level security;


-- সবাই record দেখতে পারবে
drop policy if exists "Public can read land record"
on public.land_records;

create policy "Public can read land record"
on public.land_records
for select
to anon, authenticated
using (true);


-- Admin শুধু নিজের account দিয়ে পরিবর্তন করতে পারবে
drop policy if exists "Admin can write land record"
on public.land_records;

