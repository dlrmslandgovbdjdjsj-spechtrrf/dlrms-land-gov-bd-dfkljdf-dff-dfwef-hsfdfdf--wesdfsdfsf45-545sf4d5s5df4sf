on public.land_records
for all
to authenticated
using (
  (auth.jwt() ->> 'email') = 'dlrms.land.gov.bd.jdjsj@gmail.com'
)
with check (
  (auth.jwt() ->> 'email') = 'dlrms.land.gov.bd.jdjsj@gmail.com'
